"""Storage adapter abstraction for multi-backend support (Postgres/SQLite/Turso).

Design:
  - Protocol-based: any object implementing ``execute(sql, params)`` + ``executescript``
    + ``fetch`` works as a drop-in for sqlite3.Connection.
  - SqliteAdapter: zero-change wrapper around existing sqlite3.Connection.
  - PostgresAdapter: psycopg2 connection + SQL dialect translation.
  - TursoAdapter: HTTP-based (sqlite over HTTP, future).

SQL dialect translation table (SQLite → Postgres):
  - ``?`` positional params → ``%s``
  - ``CURRENT_TIMESTAMP`` → ``NOW()``
  - ``REAL`` → ``DOUBLE PRECISION``
  - ``AUTOINCREMENT`` → ``GENERATED BY DEFAULT AS IDENTITY``
  - ``INSERT OR REPLACE`` → ``INSERT ... ON CONFLICT DO UPDATE``
  - ``PRAGMA table_info(...)`` → ``information_schema.columns``
  - ``TEXT`` → ``TEXT`` (same)
  - ``INTEGER`` → ``INTEGER`` (same)

Usage::

    # SQLite (default, same as today)
    store = MemoryStore()

    # Postgres
    from engram_router.store.adapters import PostgresAdapter
    adapter = PostgresAdapter("postgresql://user:pass@host:5432/db")
    store = MemoryStore(adapter=adapter)
"""

from __future__ import annotations

import logging
import os
import re
from abc import ABC, abstractmethod
from typing import Any, cast

logger = logging.getLogger(__name__)


# ── ABC ──────────────────────────────────────────────────────────────────


class StorageAdapter(ABC):
    """Abstract storage adapter — drop-in for sqlite3.Connection."""

    @abstractmethod
    def execute(self, sql: str, params: tuple | None = None) -> Any:
        """Execute a parameterized SQL statement; return cursor-like object."""

    @abstractmethod
    def executescript(self, sql: str) -> None:
        """Execute multiple SQL statements (schema migration batch)."""

    @abstractmethod
    def commit(self) -> None:
        """Commit the current transaction."""

    @abstractmethod
    def close(self) -> None:
        """Close the underlying connection."""


# ── SQLite adapter (zero-change wrapper) ─────────────────────────────────


class SqliteAdapter(StorageAdapter):
    """Thin wrapper around sqlite3.Connection matching StorageAdapter."""

    def __init__(self, conn: Any) -> None:
        self._conn = conn

    @property
    def conn(self) -> Any:
        return self._conn

    def execute(self, sql: str, params: tuple | None = None) -> Any:
        if params is None:
            return self._conn.execute(sql)
        return self._conn.execute(sql, params)

    def executescript(self, sql: str) -> None:
        self._conn.executescript(sql)

    def commit(self) -> None:
        self._conn.commit()

    def close(self) -> None:
        self._conn.close()


# ── Postgres adapter ─────────────────────────────────────────────────────


# SQLite → Postgres SQL dialect translations.
# Applied in order before sending to psycopg2.

_DIALECT_REWRITES: list[tuple[str, str]] = [
    # Positional params: ? → %s
    (r"\?", "%s"),
    # CURRENT_TIMESTAMP in CREATE TABLE → NOW() in DML is fine, but
    # in DDL we keep DEFAULT NOW()
]

# SQLite-specific statements that have no Postgres equivalent.
# These are removed from CREATE TABLE scripts.
_SQLITE_ONLY_PATTERNS = [
    (r"CREATE INDEX IF NOT EXISTS\s+(\w+)\s+ON\s+(\w+)\((.*?)\);",
     r"CREATE INDEX IF NOT EXISTS \1 ON \2(\3);"),  # PG supports IF NOT EXISTS
]


def _sqlite_to_pg(sql: str) -> str:
    """Translate SQLite SQL to PostgreSQL SQL."""
    # PRAGMA → information_schema
    if sql.strip().upper().startswith("PRAGMA"):
        m = re.search(r"PRAGMA\s+table_info\((\w+)\)", sql, re.IGNORECASE)
        if m:
            table = m.group(1)
            return (
                "SELECT column_name AS name, data_type AS type, "
                "is_nullable AS notnull, column_default AS dflt_value "
                "FROM information_schema.columns WHERE table_name = "
                f"'{table}'"
            )
        return "SELECT 1"  # no-op for unsupported PRAGMAs

    # REMOVE autoincrement... most PG tables use GENERATED IDENTITY which
    # is the default for SERIAL columns — no explicit keyword needed
    # ... but we keep INTEGER → SERIAL for primary key id columns

    result = sql

    # ``?`` params → ``%s``
    # Only replace ? that are NOT inside string literals
    result = re.sub(r"(?<!\w)\?(?!\w)", "%s", result)

    # REAL → DOUBLE PRECISION
    result = re.sub(r"\bREAL\b", "DOUBLE PRECISION", result)

    # TEXT → TEXT (no change)
    # INTEGER → INTEGER (no change)

    # DEFAULT CURRENT_TIMESTAMP → DEFAULT NOW()
    result = re.sub(
        r"DEFAULT CURRENT_TIMESTAMP",
        "DEFAULT NOW()",
        result,
    )

    # INSERT OR REPLACE → INSERT ... ON CONFLICT (fallback: just INSERT)
    result = re.sub(
        r"INSERT\s+OR\s+(REPLACE|IGNORE)\s+",
        "INSERT ",
        result,
    )

    return result


class PostgresAdapter(StorageAdapter):
    """PostgreSQL adapter via psycopg2.

    Requires ``pip install psycopg2-binary`` (or ``psycopg`` for async).
    """

    def __init__(self, dsn: str) -> None:
        self._dsn = dsn
        self._conn: Any = None
        self._connected = False

    def _ensure_connected(self) -> None:
        if self._connected:
            return
        try:
            import psycopg2
            import psycopg2.extras
            self._conn = psycopg2.connect(self._dsn)
            psycopg2.extras.register_default_jsonb(self._conn)
            self._connected = True
        except ImportError:
            raise ImportError(
                "psycopg2 is required for PostgresAdapter. "
                "Install with: pip install psycopg2-binary"
            )
        except Exception as exc:
            raise ConnectionError(f"Postgres connection failed: {exc}")

    @property
    def conn(self) -> Any:
        self._ensure_connected()
        return self._conn

    @property
    def dialect(self) -> str:
        return "postgresql"

    def execute(self, sql: str, params: tuple | None = None) -> Any:
        self._ensure_connected()
        pg_sql = _sqlite_to_pg(sql)
        cursor = self._conn.cursor()
        cursor.execute(pg_sql, params)
        return _PgCursorWrapper(cursor)

    def executescript(self, sql: str) -> None:
        self._ensure_connected()
        # Split on semicolons and execute each statement
        statements = [s.strip() for s in sql.split(";") if s.strip()]
        cursor = self._conn.cursor()
        for stmt in statements:
            stmt = stmt.strip()
            if not stmt:
                continue
            pg_stmt = _sqlite_to_pg(stmt)
            try:
                cursor.execute(pg_stmt)
            except Exception as exc:
                logger.debug("Postgres executescript skip: %s — %s", exc, pg_stmt[:100])
        self._conn.commit()

    def commit(self) -> None:
        if self._connected:
            self._conn.commit()

    def close(self) -> None:
        if self._connected:
            self._conn.close()
            self._connected = False


class _PgCursorWrapper:
    """Wrap a psycopg2 cursor to provide sqlite3-like Row interface."""

    def __init__(self, cursor: Any) -> None:
        self._cursor = cursor
        self.rowcount = cursor.rowcount

    def fetchone(self) -> Any | None:
        row = self._cursor.fetchone()
        if row is None:
            return None
        # Convert to dict-like for sqlite3.Row compatibility
        cols = [desc[0] for desc in self._cursor.description]
        return _PgRow(cols, row)

    def fetchall(self) -> list[Any]:
        rows = self._cursor.fetchall()
        cols = [desc[0] for desc in self._cursor.description]
        return [_PgRow(cols, r) for r in rows]


class _PgRow:
    """sqlite3.Row-compatible wrapper for psycopg2 tuple rows."""

    def __init__(self, columns: list[str], values: tuple) -> None:
        self._cols = columns
        self._vals = values
        self._map = dict(zip(columns, values))

    def __getitem__(self, key: str | int) -> Any:
        if isinstance(key, int):
            return self._vals[key]
        return self._map[key]

    def keys(self) -> list[str]:
        return list(self._cols)

    def __iter__(self):
        return iter(self._cols)

    def __repr__(self) -> str:
        return f"PgRow({self._map})"


# ── Turso adapter (HTTP sqlite) ──────────────────────────────────────────


class TursoAdapter(StorageAdapter):
    """Turso (libsql) adapter — SQLite-compatible over HTTP.

    Requires ``pip install libsql-client``.

    Usage:
        adapter = TursoAdapter(
            url="libsql://my-db.turso.io",
            auth_token="...",
        )
        store = MemoryStore(adapter=adapter)
    """

    def __init__(self, url: str, auth_token: str = "") -> None:
        self._url = url
        self._token = auth_token or os.environ.get("TURSO_AUTH_TOKEN", "")
        self._client: Any = None
        self._connected = False

    def _ensure_connected(self) -> None:
        if self._connected:
            return
        try:
            import libsql_client
            self._client = libsql_client.create_client(
                url=self._url,
                auth_token=self._token,
            )
            self._connected = True
        except ImportError:
            raise ImportError(
                "libsql_client is required for TursoAdapter. "
                "Install with: pip install libsql-client"
            )
        except Exception as exc:
            raise ConnectionError(f"Turso connection failed: {exc}")

    @property
    def conn(self) -> Any:
        self._ensure_connected()
        return self._client

    @property
    def dialect(self) -> str:
        return "sqlite"  # Turso is wire-compatible with SQLite

    def execute(self, sql: str, params: tuple | None = None) -> Any:
        self._ensure_connected()
        # Turso client uses a different API — result_set
        result = self._client.execute(sql, params or ())
        return _TursoResultWrapper(result)

    def executescript(self, sql: str) -> None:
        self._ensure_connected()
        self._client.execute(sql)

    def commit(self) -> None:
        pass  # Turso auto-commits

    def close(self) -> None:
        if self._connected:
            self._client.close()
            self._connected = False


class _TursoResultWrapper:
    def __init__(self, result: Any) -> None:
        self._result = result
        self.rowcount = len(result.rows) if hasattr(result, 'rows') else 0

    def fetchone(self) -> Any | None:
        rows = self._result.rows
        if not rows:
            return None
        cols = [c.name for c in self._result.columns]
        return _PgRow(cols, rows[0])

    def fetchall(self) -> list[Any]:
        cols = [c.name for c in self._result.columns]
        return [_PgRow(cols, r) for r in self._result.rows]


# ── Factory ──────────────────────────────────────────────────────────────


def create_adapter(dsn: str) -> StorageAdapter:
    """Create the right adapter from a DSN string.

    ``sqlite:///path/to/db`` → SqliteAdapter
    ``postgresql://user:pass@host/db`` → PostgresAdapter
    ``libsql://db.turso.io`` → TursoAdapter
    """
    if dsn.startswith("postgresql://") or dsn.startswith("postgres://"):
        return PostgresAdapter(dsn)
    if dsn.startswith("libsql://"):
        return TursoAdapter(dsn)
    # Default: sqlite3
    import sqlite3
    path = dsn.replace("sqlite:///", "")
    return SqliteAdapter(sqlite3.connect(path))
